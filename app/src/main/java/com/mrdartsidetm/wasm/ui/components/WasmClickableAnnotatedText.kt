package com.mrdartsidetm.wasm.ui.components

import androidx.compose.foundation.gestures.detectTapGestures
import androidx.compose.material3.LocalTextStyle
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.input.pointer.pointerInput
import androidx.compose.ui.platform.LocalClipboardManager
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.AnnotatedString
import androidx.compose.ui.text.TextLayoutResult
import androidx.compose.ui.text.TextStyle
import com.mrdartsidetm.wasm.util.AttachmentOpenHelper
import com.mrdartsidetm.wasm.util.ChatRichTextParser

/**
 * Renders [AnnotatedString] with interactive tap support for links, 10-digit phone numbers,
 * and 4/6-digit verification codes generated by [ChatRichTextParser].
 */
@Composable
fun WasmClickableAnnotatedText(
    text: AnnotatedString,
    color: Color,
    style: TextStyle = LocalTextStyle.current,
    onConfirmation: (String) -> Unit = {},
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val clipboard = LocalClipboardManager.current
    var layoutResult by remember { mutableStateOf<TextLayoutResult?>(null) }

    Text(
        text = text,
        color = color,
        style = style,
        onTextLayout = { layoutResult = it },
        modifier = modifier.pointerInput(text) {
            detectTapGestures { offset ->
                val layout = layoutResult ?: return@detectTapGestures
                val charOffset = layout.getOffsetForPosition(offset)

                val urlAnnotation = text.getStringAnnotations(ChatRichTextParser.TAG_URL, charOffset, charOffset).firstOrNull()
                if (urlAnnotation != null) {
                    AttachmentOpenHelper.openExternalUrl(context, urlAnnotation.item)
                    return@detectTapGestures
                }

                val phoneAnnotation = text.getStringAnnotations(ChatRichTextParser.TAG_PHONE, charOffset, charOffset).firstOrNull()
                if (phoneAnnotation != null) {
                    AttachmentOpenHelper.dialPhoneNumber(context, phoneAnnotation.item)
                    return@detectTapGestures
                }

                val codeAnnotation = text.getStringAnnotations(ChatRichTextParser.TAG_CODE, charOffset, charOffset).firstOrNull()
                if (codeAnnotation != null) {
                    clipboard.setText(AnnotatedString(codeAnnotation.item))
                    onConfirmation("Copied code: ${codeAnnotation.item}")
                }
            }
        }
    )
}
