/**
 * Supported language metadata with flag emoji, native name, and RTL marker.
 */
@Immutable
data class SupportedLanguage(
    val code: String,
    val flagEmoji: String,
    val nativeName: String,
    val isRtl: Boolean = false
)

val SupportedLanguages: List<SupportedLanguage> = listOf(
    SupportedLanguage(code = "en", flagEmoji = "🇬🇧", nativeName = "English"),
    SupportedLanguage(code = "ja", flagEmoji = "🇯🇵", nativeName = "日本語"),
    SupportedLanguage(code = "hi", flagEmoji = "🇮🇳", nativeName = "हिन्दी"),
    SupportedLanguage(code = "ru", flagEmoji = "🇷🇺", nativeName = "Русский"),
    SupportedLanguage(code = "es", flagEmoji = "🇪🇸", nativeName = "Español"),
    SupportedLanguage(code = "bn", flagEmoji = "🇧🇩", nativeName = "বাংলা"),
    SupportedLanguage(code = "pt", flagEmoji = "🇵🇹", nativeName = "Português"),
    SupportedLanguage(code = "id", flagEmoji = "🇮🇩", nativeName = "Bahasa Indonesia"),
    SupportedLanguage(code = "ur", flagEmoji = "🇵🇰", nativeName = "اردو", isRtl = true),
    SupportedLanguage(code = "de", flagEmoji = "🇩🇪", nativeName = "Deutsch"),
    SupportedLanguage(code = "pa", flagEmoji = "🇮🇳", nativeName = "ਪੰਜਾਬੀ")
)

fun languageByCode(code: String): SupportedLanguage {
    return SupportedLanguages.firstOrNull { it.code == code } ?: SupportedLanguages.first()
}

